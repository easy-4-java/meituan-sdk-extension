    /**
     * 根据业务 ID 和消息类型查找传给 {@link CallbackUtil} 的模型类。
     *
     * @param businessId 回调所属业务的 {@code businessId}
     * @param msgType 回调的 {@code msgType}；旧版会员卡协议使用 {@code invokeType}
     * @return 对应的业务模型类；参数为空或组合未登记时返回空的 {@link Optional}
     */
